int fb_init(fb_context_t* ctx, const char* device) {
    memset(ctx, 0, sizeof(fb_context_t));
    if (!device) device = "/dev/fb0";

    ctx->fd = open(device, O_RDWR);
    if (ctx->fd >= 0) {
        struct fb_var_screeninfo vinfo;
        struct fb_fix_screeninfo finfo;

        if (ioctl(ctx->fd, FBIOGET_FSCREENINFO, &finfo) == 0 &&
            ioctl(ctx->fd, FBIOGET_VSCREENINFO, &vinfo) == 0) {
            ctx->width = vinfo.xres;
            ctx->height = vinfo.yres;
            ctx->bpp = vinfo.bits_per_pixel;
            ctx->screensize = finfo.smem_len;
            ctx->fbp = (uint8_t*)mmap(0, ctx->screensize, PROT_READ | PROT_WRITE, MAP_SHARED, ctx->fd, 0);
            if (ctx->fbp != MAP_FAILED) {
                ctx->is_virtual = 0;
                printf("[SAPHAL-FB] Attached to hardware framebuffer: %dx%d (%d bpp)\n", ctx->width, ctx->height, ctx->bpp);
                return 0;
            }
        }
        close(ctx->fd);
    }

    // Fallback: Virtual Framebuffer (Matches Verified Xiaomi Redmi 9 cattail: 720x1600 HD+)
    ctx->is_virtual = 1;
    ctx->width = 720;
    ctx->height = 1600;
    ctx->bpp = 32;
    ctx->screensize = ctx->width * ctx->height * 4;
    ctx->fbp = (uint8_t*)calloc(1, ctx->screensize);
    printf("[SAPHAL-FB] Operating in Virtual cattail Framebuffer mode (%dx%d, 32bpp).\n", ctx->width, ctx->height);
    return 0;
}

void fb_close(fb_context_t* ctx) {
    if (!ctx) return;
    if (ctx->is_virtual && ctx->fbp) {
        free(ctx->fbp);
    } else if (ctx->fbp && ctx->fbp != MAP_FAILED) {
        munmap(ctx->fbp, ctx->screensize);
    }
    if (ctx->fd >= 0) {
        close(ctx->fd);
    }
    memset(ctx, 0, sizeof(fb_context_t));
}

void fb_draw_pixel(fb_context_t* ctx, int x, int y, uint32_t color) {
    if (!ctx || !ctx->fbp) return;
    if (x < 0 || (uint32_t)x >= ctx->width || y < 0 || (uint32_t)y >= ctx->height) return;

    if (ctx->bpp == 32) {
        uint32_t* ptr = (uint32_t*)(ctx->fbp + (y * ctx->width + x) * 4);
        *ptr = color;
    } else if (ctx->bpp == 16) {
        uint16_t r = (color >> 19) & 0x1F;
        uint16_t g = (color >> 10) & 0x3F;
        uint16_t b = (color >> 3) & 0x1F;
        uint16_t* ptr = (uint16_t*)(ctx->fbp + (y * ctx->width + x) * 2);
        *ptr = (r << 11) | (g << 5) | b;
    }
}

void fb_fill_rect(fb_context_t* ctx, int x, int y, int w, int h, uint32_t color) {
    for (int j = y; j < y + h; j++) {
        for (int i = x; i < x + w; i++) {
            fb_draw_pixel(ctx, i, j, color);
        }
    }
}

void fb_clear(fb_context_t* ctx, uint32_t color) {
    fb_fill_rect(ctx, 0, 0, ctx->width, ctx->height, color);
}

void fb_draw_char(fb_context_t* ctx, int x, int y, char c, uint32_t color, int scale) {
    if (c < 32 || c > 126) c = '?';
    const uint8_t* glyph = font8x8[c - 32];

    for (int row = 0; row < 8; row++) {
        uint8_t line = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (line & (1 << col)) {
                if (scale <= 1) {
                    fb_draw_pixel(ctx, x + col, y + row, color);
                } else {
                    fb_fill_rect(ctx, x + col * scale, y + row * scale, scale, scale, color);
                }
            }
        }
    }
}

void fb_draw_string(fb_context_t* ctx, int x, int y, const char* str, uint32_t color, int scale) {
    if (!str) return;
    int cur_x = x;
    int cur_y = y;

    for (int i = 0; str[i] != '\0'; i++) {
        if (str[i] == '\n') {
            cur_x = x;
            cur_y += 10 * scale;
        } else {
            fb_draw_char(ctx, cur_x, cur_y, str[i], color, scale);
            cur_x += 8 * scale;
        }
    }
}

void fb_draw_circle(fb_context_t* ctx, int cx, int cy, int radius, uint32_t color) {
    int x = radius;
    int y = 0;
    int err = 0;

    while (x >= y) {
        fb_draw_pixel(ctx, cx + x, cy + y, color);
        fb_draw_pixel(ctx, cx + y, cy + x, color);
        fb_draw_pixel(ctx, cx - y, cy + x, color);
        fb_draw_pixel(ctx, cx - x, cy + y, color);
        fb_draw_pixel(ctx, cx - x, cy - y, color);
        fb_draw_pixel(ctx, cx - y, cy - x, color);
        fb_draw_pixel(ctx, cx + y, cy - x, color);
        fb_draw_pixel(ctx, cx + x, cy - y, color);

        if (err <= 0) {
            y += 1;
            err += 2 * y + 1;
        }
        if (err > 0) {
            x -= 1;
            err -= 2 * x + 1;
        }
    }
}

void fb_fill_circle(fb_context_t* ctx, int cx, int cy, int radius, uint32_t color) {
    for (int y = -radius; y <= radius; y++) {
        for (int x = -radius; x <= radius; x++) {
            if (x * x + y * y <= radius * radius) {
                fb_draw_pixel(ctx, cx + x, cy + y, color);
            }
        }
    }
}

int fb_load_ppm(const char* filename, fb_image_t* img) {
    if (!filename || !img) return -1;
    FILE* fp = fopen(filename, "rb");
    if (!fp) return -1;

    char header[16];
    if (fscanf(fp, "%15s", header) != 1 || strcmp(header, "P6") != 0) {
        fclose(fp);
        return -1;
    }

    int w = 0, h = 0, maxval = 0;
    if (fscanf(fp, "%d %d %d", &w, &h, &maxval) != 3 || maxval != 255 || w <= 0 || h <= 0) {
        fclose(fp);
        return -1;
    }
    fgetc(fp); // skip newline

    img->width = (uint32_t)w;
    img->height = (uint32_t)h;
    img->pixels = (uint32_t*)malloc(w * h * sizeof(uint32_t));

    for (int i = 0; i < w * h; i++) {
        uint8_t r = fgetc(fp);
        uint8_t g = fgetc(fp);
        uint8_t b = fgetc(fp);
        img->pixels[i] = 0xFF000000 | (r << 16) | (g << 8) | b;
    }
    fclose(fp);
    return 0;
}

void fb_draw_image(fb_context_t* ctx, int dx, int dy, const fb_image_t* img) {
    if (!ctx || !img || !img->pixels) return;
    for (uint32_t y = 0; y < img->height; y++) {
        for (uint32_t x = 0; x < img->width; x++) {
            uint32_t color = img->pixels[y * img->width + x];
            fb_draw_pixel(ctx, dx + x, dy + y, color);
        }
    }
}

void fb_draw_avatar_or_placeholder(fb_context_t* ctx, int cx, int cy, int radius, const char* image_path, const char* initial) {
    // 1. Draw glowing accent outer ring (Cyan)
    for (int r = radius + 1; r <= radius + 5; r++) {
        fb_draw_circle(ctx, cx, cy, r, 0xFF00F5D4);
    }

    fb_image_t img;
    int loaded = 0;
    if (image_path && fb_load_ppm(image_path, &img) == 0) {
        loaded = 1;
        // Blit image cropped into circle
        for (int y = -radius; y <= radius; y++) {
            for (int x = -radius; x <= radius; x++) {
                if (x * x + y * y <= radius * radius) {
                    // Map x, y into image coordinates
                    uint32_t img_x = (uint32_t)((x + radius) * img.width / (2 * radius));
                    uint32_t img_y = (uint32_t)((y + radius) * img.height / (2 * radius));
                    if (img_x < img.width && img_y < img.height) {
                        uint32_t col = img.pixels[img_y * img.width + img_x];
                        fb_draw_pixel(ctx, cx + x, cy + y, col);
                    }
                }
            }
        }
        free(img.pixels);
    }

    if (!loaded) {
        // Fallback: Gradient Blue Badge with Owner's Initial
        fb_fill_circle(ctx, cx, cy, radius, 0xFF1C2541);
        fb_fill_circle(ctx, cx, cy, radius - 6, 0xFF0B132B);

        // Draw initial letter in the center
        char c = (initial && initial[0]) ? initial[0] : 'S';
        fb_draw_char(ctx, cx - 24, cy - 28, c, 0xFF00F5D4, 7);
    }
}

int fb_save_ppm(fb_context_t* ctx, const char* filename) {
    if (!ctx || !ctx->fbp) return -1;
    FILE* fp = fopen(filename, "wb");
    if (!fp) return -1;

    fprintf(fp, "P6\n%d %d\n255\n", ctx->width, ctx->height);
    for (uint32_t y = 0; y < ctx->height; y++) {
        for (uint32_t x = 0; x < ctx->width; x++) {
            uint32_t color = *(uint32_t*)(ctx->fbp + (y * ctx->width + x) * 4);
            uint8_t r = (color >> 16) & 0xFF;
            uint8_t g = (color >> 8) & 0xFF;
            uint8_t b = color & 0xFF;
            fputc(r, fp);
            fputc(g, fp);
            fputc(b, fp);
        }
    }
    fclose(fp);
    printf("[SAPHAL-FB] Snapshot saved to %s\n", filename);
    return 0;
}
